def esc(s):
    """Escape '$' supaya matplotlib tidak membacanya sebagai rumus (math mode)."""
    return str(s).replace('$', r'\$')

def rp(v):
    """Format angka gaya Indonesia: 1234567 -> 1.234.567"""
    return f'{v:,.0f}'.replace(',', '.')

def uang(v, desimal=2):
    """Format nilai uang gaya Indonesia: 1700 -> 1.700,00 ; 2.99 -> 2,99"""
    s = f'{v:,.{desimal}f}'
    return s.replace(',', '@').replace('.', ',').replace('@', '.')

